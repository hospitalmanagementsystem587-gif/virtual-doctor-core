"""
Virtual Doctor Core Schemas
Structured, validated clinical data models for symptom intake, red-flag triage, and SOAP generation.
"""

from enum import Enum
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class TriageLevel(str, Enum):
    EMERGENCY_RED = "EMERGENCY_RED"       # Immediate ER transfer / Call 108
    URGENT_YELLOW = "URGENT_YELLOW"       # Priority OPD evaluation within 2-4 hrs
    ROUTINE_GREEN = "ROUTINE_GREEN"       # Standard scheduled OPD clinic appointment
    SELF_CARE = "SELF_CARE"               # Ambulatory supportive care with warning return flags


class RedFlagAlert(BaseModel):
    is_critical: bool
    trigger_symptom: str
    risk_category: str
    urgency_recommendation: str
    emergency_call_action: Optional[str] = "108"


class PatientProfile(BaseModel):
    age: int = Field(..., ge=0, le=125, description="Patient age in years")
    gender: str = Field(..., description="biological sex or gender (male/female/other)")
    is_pregnant: Optional[bool] = False
    known_allergies: List[str] = Field(default_factory=list, description="Drug or food allergies")
    chronic_conditions: List[str] = Field(default_factory=list, description="e.g. Hypertension, Diabetes, Asthma, CAD")
    current_medications: List[str] = Field(default_factory=list, description="Ongoing prescriptions")


class SymptomEncounterInput(BaseModel):
    patient: PatientProfile
    chief_complaint: str = Field(..., min_length=3, description="Main presenting symptom (e.g. chest pain, cough, rash)")
    onset: Optional[str] = Field(None, description="Sudden vs gradual, duration in hours/days")
    provocation_palliation: Optional[str] = Field(None, description="What triggers or relieves the symptom")
    quality_character: Optional[str] = Field(None, description="Sharp, dull, throbbing, pressure, burning")
    radiation: Optional[str] = Field(None, description="Anatomical spread (e.g. radiating to jaw or left arm)")
    severity_scale: Optional[int] = Field(None, ge=1, le=10, description="Pain or distress scale 1 to 10")
    timing_frequency: Optional[str] = Field(None, description="Constant, intermittent, episodic")
    associated_symptoms: List[str] = Field(default_factory=list, description="Associated symptoms (fever, nausea, dyspnea, etc.)")
    pertinent_negatives: List[str] = Field(default_factory=list, description="Symptoms patient denies (no fever, no hemoptysis)")


class DifferentialDiagnosisItem(BaseModel):
    diagnosis_name: str
    icd10_code: Optional[str] = None
    probability_rank: int = Field(..., ge=1, le=5)
    confidence_score: float = Field(..., ge=0.0, le=1.0)
    clinical_rationale: str
    supporting_symptoms: List[str]
    pertinent_negatives_evaluated: List[str]
    citations_guidelines: List[str] = Field(default_factory=list)


class DiagnosticWorkupRecommendation(BaseModel):
    investigation_type: str  # "Laboratory", "Radiology / Imaging", "Bedside / Point-of-Care"
    test_name: str
    urgency: str  # "Stat", "Same Day", "Routine"
    clinical_purpose: str


class SoapClinicalSummary(BaseModel):
    subjective: str = Field(..., description="Clinician-grade narrative of history of presenting illness")
    objective: str = Field(..., description="Reported vitals, clinical risk stratifications, pertinent positives/negatives")
    assessment: str = Field(..., description="Clinical reasoning and diagnostic synthesis")
    plan: str = Field(..., description="Recommended workup, specialty referral, and patient counseling guidance")


class VirtualDoctorAssessmentResponse(BaseModel):
    encounter_id: str
    timestamp: str
    triage_level: TriageLevel
    red_flag_alert: Optional[RedFlagAlert] = None
    soap_note: SoapClinicalSummary
    differential_diagnoses: List[DifferentialDiagnosisItem]
    recommended_workup: List[DiagnosticWorkupRecommendation]
    recommended_specialty_clinic: str
    disclaimer: str = (
        "Clinical Decision Support Notice: This assessment is generated by an assistive AI copilot "
        "grounded in clinical practice guidelines for triage and differential reasoning. It does NOT "
        "replace independent medical evaluation, physical examination, or diagnostic testing by a licensed physician."
    )
